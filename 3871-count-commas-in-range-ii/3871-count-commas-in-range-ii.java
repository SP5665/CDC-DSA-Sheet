class Solution {
    public long countCommas(long n) {
        if (n < 1000) return 0;

        if (n < 1000000)
            return n - 1000 + 1;

        if (n < 1000000000)
            return 999000 + (n - 1000000 + 1) * 2;

        if (n < 1000000000000L)
            return 999000 
                 + 999000000L * 2
                 + (n - 1000000000L + 1) * 3;

        if (n < 1000000000000000L)
            return 999000
                + 999000000L * 2
                + 999000000000L * 3
                + (n - 1000000000000L + 1) * 4;

        return 999000
            + 999000000L * 2
            + 999000000000L * 3
            + 999000000000000L * 4
            + 1 * 5;
    }
}